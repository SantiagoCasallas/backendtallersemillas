-- V1 is preserved. Numeric identifiers belong to the new versioned frontend API.
CREATE TABLE school_students (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 document_type VARCHAR(10) NOT NULL,
 document_number VARCHAR(40) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('ASPIRANTE','ACTIVO','RETIRADO','EGRESADO')),
 data TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(document_type, document_number)
);
CREATE TABLE school_guardians (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id BIGINT NOT NULL REFERENCES school_students(id),
 document_type VARCHAR(10) NOT NULL,
 document_number VARCHAR(40) NOT NULL,
 data TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(student_id,document_type,document_number)
);
CREATE INDEX idx_guardian_student ON school_guardians(student_id);
CREATE TABLE school_medical_histories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id BIGINT NOT NULL UNIQUE REFERENCES school_students(id),
 data TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE school_medical_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 history_id BIGINT NOT NULL REFERENCES school_medical_histories(id),
 data TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_medical_history ON school_medical_entries(history_id);
CREATE TABLE school_schemas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 form_type VARCHAR(20) NOT NULL,
 version INTEGER NOT NULL,
 data TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(form_type,version)
);
CREATE TABLE school_slots (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 data TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE school_interviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slot_id BIGINT NOT NULL REFERENCES school_slots(id),
 schema_id BIGINT NOT NULL REFERENCES school_schemas(id),
 contact_email VARCHAR(254) NOT NULL,
 data TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(slot_id,contact_email)
);
CREATE TABLE school_inscriptions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id BIGINT NOT NULL REFERENCES school_students(id),
 guardian_id BIGINT NOT NULL REFERENCES school_guardians(id),
 schema_id BIGINT NOT NULL REFERENCES school_schemas(id),
 data TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_inscription_student ON school_inscriptions(student_id);
CREATE TABLE school_locks (lock_key VARCHAR(40) PRIMARY KEY);
